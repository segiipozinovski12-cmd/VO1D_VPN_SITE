                    topBar
                    titleBlock

                    ReferenceGlassCard(radius: 24) {
                        Text(document.body)
                            .font(
                                .system(
                                    size: 13,
                                    weight: .regular,
                                    design: .default
                                )
                            )
                            .foregroundStyle(.white.opacity(0.78))
                            .lineSpacing(7)
                            .textSelection(.enabled)
                            .frame(
                                maxWidth: .infinity,
                                alignment: .leading
                            )
                            .padding(20)
                    }
                }
